/**
 * Бесплатный запасной отбор: ранжирование единиц по регуляркам темы.
 *
 * Перенесено из бенча (scripts/guidelines/keyword-filter.ts, ветка
 * w38/26-guidelines-retrieval): 81,9 % recall@10 против 97,0 % у связки
 * эмбеддинги + реранк. Используется, когда шлюз недоступен, ключа нет
 * или бюджет времени на ретрив исчерпан — лучше грубый отбор, чем отказ.
 */

import type { Unit } from "./segment";

/** Каждая группа — самостоятельный сигнал темы; чем больше групп, тем выше ранг. */
export const TOPIC_PATTERNS: Record<string, RegExp[]> = {
  font: [/шрифт|гарнитур|times new roman|arial/i, /кегл|размер\s+шрифт|\b1[24]\s*(пт|пунк)/i],
  margins: [/\bпол[еяй]\b|поля\s+страниц/i, /(лев|прав|верхн|нижн)\w*\s+пол|\b[123]?\d\s*мм/i],
  line_spacing: [/межстрочн|интервал/i, /полуторн|1[.,]5|одинарн|двойн/i],
  indent_align: [/абзацн\w*\s+отступ|красн\w*\s+строк/i, /выравнив|по\s+ширине|отступ\s+перв/i],
  page_numbers: [
    /нумерац\w*\s+страниц|номер\w*\s+страниц/i,
    /колонтитул|титульн\w*\s+лист\w*\s+не|сквозн/i,
  ],
  headings: [/заголов|наименован\w*\s+раздел/i, /прописн|полужирн|с\s+нов\w*\s+страниц|без\s+точки/i],
  tables: [/таблиц/i, /подпис|нумер|перенос|шапк|«?таблица\s*\d/i],
  figures: [/рисун|иллюстрац|диаграмм|график|схем/i, /подпис|нумер|«?рисунок\s*\d|под\s+рисунк/i],
  formulas: [/формул|уравнен/i, /скобк|нумер|редактор\w*\s+формул|отдельн\w*\s+строк/i],
  lists: [
    /перечислен|списк\w*\s+(?!литератур|использ|источник)|маркирован/i,
    /дефис|буллит|арабск|строчн\w*\s+букв|скобк/i,
  ],
  bibliography: [
    /список\w*\s+(литератур|использован|источник)|библиограф/i,
    /гост|алфавит|источник\w*\s+не\s+менее|оформля/i,
  ],
  appendices: [/приложени/i, /обознача|заглавн\w*\s+букв|после\s+списк|нумер/i],
  title_page: [
    /титульн\w*\s+лист|титул\b/i,
    /оформля|образец|указыва|наименован\w*\s+(вуза|учрежден)/i,
  ],
  citations: [
    /сноск|ссылк\w*\s+на\s+источник|цитир|библиографическ\w*\s+ссылк/i,
    /квадратн\w*\s+скобк|подстрочн|\[\d+\]|номер\w*\s+источник/i,
  ],
};

/**
 * Номера единиц по убыванию числа сработавших групп, при равенстве —
 * по порядку в документе. Единицы без совпадений не возвращаются.
 */
export function rankByKeywords(units: Unit[], topic: string): number[] {
  const patterns = TOPIC_PATTERNS[topic] ?? [];
  const scored: Array<{ i: number; score: number }> = [];
  for (const unit of units) {
    const score = patterns.reduce((s, re) => s + (re.test(unit.text) ? 1 : 0), 0);
    if (score > 0) scored.push({ i: unit.i, score });
  }
  scored.sort((a, b) => b.score - a.score || a.i - b.i);
  return scored.map((s) => s.i);
}
