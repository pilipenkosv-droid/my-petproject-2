export async function build(): Promise<DocBuildResult> {
  const bibliography = ENTRIES.map((entry, i) => bodyPara(`${i + 1}. ${entry}`));

  const chapterBody = [bodyPara("Основной текст главы 1 не связан со списком источников напрямую — тот приведён в конце документа.")];

  const doc = new Document({
    creator: "Un-named",
    sections: [{ properties: {}, children: buildGostShell({ title: "Список источников из 15 записей", chapterBody, bibliography }) }],
  });

  const buffer = await finalize(await Packer.toBuffer(doc));
  const bibliographyParagraphs = await countInParts(buffer, ["word/document.xml"], /<w:t xml:space="preserve">\d+\. /g);

  const mustSurvive = {
    "bibliography-entries": bibliographyParagraphs,
  };

  return { file: "11-bibliography-15.docx", hazard: "bibliography (15 entries, 4 shapes)", buffer, mustSurvive };
}
